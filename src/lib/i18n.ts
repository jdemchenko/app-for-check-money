export type Locale = "ru" | "en";

export function detectLocale(): Locale {
  if (typeof navigator === "undefined") return "ru";
  const lang = navigator.language?.toLowerCase() ?? "ru";
  return lang.startsWith("ru") ? "ru" : "en";
}

